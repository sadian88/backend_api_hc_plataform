CREATE TABLE IF NOT EXISTS companies (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    company_name VARCHAR(200) NOT NULL,
    company_url_profile VARCHAR(200) NOT NULL,
    company_segment VARCHAR(100),
    customer_url_profile VARCHAR(200),
    company_icp TEXT,
    icp_industries TEXT[],
    icp_company_size VARCHAR(50),
    icp_target_country VARCHAR(100),
    icp_target_city VARCHAR(120),
    icp_industry_pain TEXT,
    icp_competitors TEXT[],
    icp_current_customers TEXT[],
    buyer_persona_name VARCHAR(150),
    buyer_persona_age INTEGER,
    buyer_persona_role VARCHAR(150),
    buyer_persona_company_type VARCHAR(150),
    buyer_persona_location VARCHAR(150),
    buyer_persona_goals TEXT,
    buyer_persona_pain_points TEXT,
    buyer_persona_buying_behavior TEXT,
    buyer_persona_channels TEXT[],
    creation_date DATE DEFAULT CURRENT_DATE,
    last_update TIMESTAMPTZ DEFAULT NOW(),
    CONSTRAINT companies_pkey PRIMARY KEY (id, company_name),
    CONSTRAINT companies_id_key UNIQUE (id)
);

CREATE INDEX IF NOT EXISTS companies_name_idx ON companies (company_name);
